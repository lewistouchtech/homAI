# -*- coding: utf-8 -*-
"""退出意图与「媒体停止」的区分（2026-10-07）

## 问题
退出词表（`exit_commands`）里有「停止」，而判定规则是「精确命中**或以退出命令开头**」。
于是主人说「停止播放」「停止播放音乐」，被当成退出命令 —— 直接退出会话。

主人原话：「我说停止播放音乐，他并没有理解我是要让他把音乐播放停止，他直接退出了。」

## 规则
含媒体词的「停止/关闭/关掉」是**控制媒体**，不是退出对话：
  「停止播放」「停止播放音乐」「关闭音乐」「关掉这首歌」→ 交给 LLM 去停音乐
  「停止」「不聊了」「再见」→ 仍然是退出

媒体词表刻意只收「播放/音乐/歌/视频/…」这类明确指向媒体内容的词，
不收「声音」「说话」—— 因为「别说了/停止说话」更接近「别播报了」的退出语义。
"""

_MEDIA_WORDS = (
    "播放", "音乐", "歌曲", "首歌", "唱歌", "歌", "视频", "电影", "电台",
    "音频", "有声书", "播客", "专辑", "单曲",
)

# [2026-10-11] 纯停止词：**只打断当前播报，不是退出对话**。
#
# 2026-10-07 只修了「停止播放音乐」被当退出的情况（靠 _MEDIA_WORDS 挡），
# 但裸「停止」仍然被当退出 —— 今天主人实测再次踩到：
#     他说「停止，关闭窗口」（想停掉新闻播报）
#     → 日志：intentHandler 识别到明确的退出命令: 停止
#     → 直接进 standby，之后说的「关闭窗口。」全被 idle_guard 静默忽略
#
# 语义上「停止」在对话场景下 99% 是「别播了/停一下」，退出对话人们会说
# 退出/再见/结束对话。把它继续留在退出词表里是设计判断错误。
# 所以：命中这些词 → 走打断（abort），会话保持激活，不前移 standby。
_BARE_STOP_WORDS = ("停止", "停下", "停下来", "停一下", "停一停", "别播了", "别念了")


def is_media_stop_command(text: str) -> bool:
    """这句「停止/关闭」是不是在说媒体（而不是要退出对话）。"""
    t = str(text or "")
    return any(w in t for w in _MEDIA_WORDS)


def is_bare_stop_command(text: str) -> bool:
    """这句是不是**纯停止**（打断播报），而不是退出对话。

    只在整句（去标点后）就是停止词时返回 True，避免把
    「停止播放音乐」这类含媒体词的也拖进来（那条由 is_media_stop_command 负责）。
    """
    t = str(text or "").strip().rstrip("。.!！?？~～,，、 ")
    if not t:
        return False
    if is_media_stop_command(t):
        return False          # 含媒体词 → 归 LLM 管媒体，不在这里处理
    return any(t == w or t.startswith(w + "，") or t == w + "。" for w in _BARE_STOP_WORDS)
