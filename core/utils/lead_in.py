# 单字发音时长（秒）。实测 19 句真实缓存音频：中位 0.28s/字，p25 0.25、p75 0.35。
# 取中位：宁可低估时长也不要高估。
# 【2026-10-12 主人修正后已不用于选档】，只保留给日志/调试估算时长。
_SEC_PER_CHAR = 0.28

# 「复述」的判定阈值（连续多少字重合算照搬用户原话）
_REPEAT_NGRAM = 5


def phrase_seconds(text: str) -> float:
    """一句话大概多久（秒）。按字数估算，用于按等待时长选长短句。"""
    n = len([c for c in (text or "") if c.strip()])
    return n * _SEC_PER_CHAR


class Pool(tuple):
    """过渡句文案池。

    做成 tuple 子类是为了**向后兼容**：既有代码/单测里
    `for pattern, pool, key in _INTENT_POOLS: for ph in pool` 的老写法照常工作。

    ⚠️ 不能用 `__slots__`：tuple 是变长内置类型，非空 __slots__ 会在建类时直接
    抛 `TypeError: nonempty __slots__ not supported for subtype of 'tuple'`。
    ⚠️ 构造必须显式 `tuple.__new__(cls, flat)`：写 `super().__new__(cls, *flat)`
    会把展平后的多个元素当 tuple 的多个构造参数 →「tuple expected at most
    1 argument」。所以绕开 super，直接调 tuple 的构造器。

    【2026-10-12】原先分 short/medium/long 三档，主人明确说不需要分档
    （说长了后面是排队、不占时间，反而衔接更顺），所以现在**只有一档**。
    构造仍接受 `short=` 这个旧写法（内部忽略、展平进来），
    是为了让 28 处旧调用点不用一次全改；新代码直接 `Pool("句一", "句二")`。
    """

    def __new__(cls, *phrases, **kwargs):
        flat = []
        for p in phrases:
            if isinstance(p, (tuple, list)):
                flat.extend(p)
            else:
                flat.append(p)
        # 兼容旧的三档写法：short/medium/long 全部展平进来，按传入顺序去重
        for k in ("short", "medium", "long"):
            v = kwargs.get(k)
            if v:
                flat.extend(v)
        seen, uniq = set(), []
        for p in flat:
            if p not in seen:
                seen.add(p)
                uniq.append(p)
        return tuple.__new__(cls, uniq)

    def for_budget(self, budget=None):
        """返回候选列表。

        【2026-10-12 主人修正】原先是「按预算挑刚好够长的一档」，现在**完全不分档**。
        主人原话：「并没有限定超短句的回复……反正说长了，后面是排队嘛，这样就没有
        影响，反而显得更顺畅。一点延迟都没有，直接就接上了，反而更好。」

        原因：过渡句与正文回复走**同一个 `AudioRateController` FIFO**，
        过渡句长不会给总时长加码（回复音频本来就排在它后面），说完直接接上、听感连贯；
        短句反而突兀（「好的」→ 静默 → 突然一大段）。

        `budget` 参数保留只为兼容调用方（`chat_engine` 仍在传预测等待秒数），
        一律返回全部候选，由 `_choose` 随机轮换。
        """
        return list(self)


def _norm(text):
    """去掉标点空白，只留实词字符，用于比对「有没有复述原话」。"""
    return re.sub(r"[\s，。！？、,.!?~～；;：:…—\-]+", "", text or "")


def _repeats(candidate, normalized_query, n=_REPEAT_NGRAM):
    """候选句是否 ≥n 字连续复述了用户原话。"""
    c = _norm(candidate)
    if len(c) < n:
        return False
    return any(c[i:i + n] in normalized_query for i in range(len(c) - n + 1))


def pick_non_repeating(pool, avoid=None, query=None):
    """从池里挑一句，尽量**不复述用户原话**（主人 ②）。

    判定：候选句与用户原话存在 ≥5 字连续重合即算复述（如用户说「今天的新闻」，
    候选是「我翻翻今天的新闻」——主题对得上，但整段照搬听着像回声）。
    只在「不复述」的候选里挑；全都复述就退回原池（宁可复述也不冷场）。
    """
    cands = [p for p in pool if p != avoid] or list(pool)
    if not cands:
        return None
    q = _norm(query) if query else ""
    if not q:
        return random.choice(cands)
    fresh = [p for p in cands if not _repeats(p, q)]
    return random.choice(fresh or cands)


