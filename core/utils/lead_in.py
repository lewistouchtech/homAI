def pick_resume(tool_names=None, avoid=None) -> str:
    """插话播完后、继续原任务前的衔接语（按工具名带一个主题词）。"""
    names = [str(n) for n in (tool_names or [])]
    topic = next((_RESUME_TOPIC_BY_TOOL[n] for n in names if n in _RESUME_TOPIC_BY_TOOL), None)
    if topic:
        return _choose(tuple(t.format(topic=topic) for t in _RESUME_TEMPLATES), avoid)
    return _choose(_RESUME_GENERIC_POOL, avoid)


def pick_farewell(avoid=None) -> str:
    """回待机前的极短告别（2~4 字）。"""
    return _choose(_FAREWELL_POOL, avoid)


