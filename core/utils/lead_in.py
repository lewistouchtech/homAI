# 轮换状态：避免连续两次说同一句
_rotate_lock = threading.Lock()
_last_lead_in = [None]


def _choose(pool, avoid=None, query=None):
    """从池里随机挑一句，尽量避开上一次说过的，且不复述用户原话。"""
    if not pool:
        return None
    return pick_non_repeating(pool, avoid=avoid, query=query)


def _remember(picked):
    if picked:
        with _rotate_lock:
            _last_lead_in[0] = picked
            import time as _t
            _last_pad_ts[0] = _t.time()
    return picked


def _is_chitchat(text: str) -> bool:
    for p in _CHITCHAT_PATTERNS:
        if p.search(text):
            return True
    return False


def pick_lead_in(query, avoid=None, budget=None, return_key=False):
    """判断这句要不要播垫场词，返回要播的文案；不需要则返回 None。

    只做「要不要播 + 播什么」的判断，不碰 TTS、不碰连接状态，天然好测。
    avoid:  上一次说过的文案（避免连续重复）；不传则用模块内记录的上一句。
    budget: 已废弃参数（原本按等待时长选长短句，主人 2026-10-12 明确不需要分档
            ——说长了后面是排队、不占总时长）。保留仅为兼容调用方。
    return_key: True 时返回 (文案, 意图 key)，供调用方记录本轮用了哪个意图。
    """
    empty = (None, None) if return_key else None
    if not query:
        return empty
    text = query.strip()
    if not text:
        return empty

    def _out(pool, key):
        cands = pool.for_budget(budget) if isinstance(pool, Pool) else list(pool)
        got = _remember(_choose(cands, last, query=text))
        return (got, key) if return_key else got

    with _rotate_lock:
        last = avoid if avoid is not None else _last_lead_in[0]

    # 闲聊 / 纯问候：不播，铺垫反而啰嗦
    if _is_chitchat(text):
        return empty

    # 冷却：刚应过声就不再应（连续对话/游戏里每句都「应一声」很吵）
    import time as _t
    if (avoid is None) and (_t.time() - _last_pad_ts[0] < _PAD_COOLDOWN_S):
        return empty

    lowered = text.lower()

    # [2026-10-13] 谈论 / 评价 / 追问：不是办事，不能按关键词挑工具类垫场句。
    # 在等回复（问句/解释类）→ 只应「我想想」；纯陈述 → 不播。
    if _is_discussion(text):
        if _WANTS_REPLY_RE.search(text):
            return _out(_CHAT_POOL, "chat")
        return empty
    # （放在退出/陪玩判断之前：「但是还能识别退出命令」是在谈论退出，不是要退出。）

    # 告别 / 退出：最先判，绝不能落进动作池。
    # （主人 2026-10-07 实测：说「退出吧」垫场句回「我这就去处理」，完全不对路）
    if _EXIT_PATTERN.search(text):
        return _out(_EXIT_POOL, "exit")

    # 陪玩 / 闲聊：也不是要它去办事，只应「我在听」。
    # （主人实测：「我们继续玩数字炸弹吧」被回「好，我这就去看看」）
    if _PLAY_PATTERN.search(text):
        return _out(_CHAT_POOL, "chat")

    # [2026-10-11 C1] 汇报状态的陈述句不播：「灯开了，空调26度」不是请求。
    # 放在工具倾向分支**之前**：不然会因句中的「灯/空调」命中设备池回「行，这就来」。
    if _STATE_DONE_RE.search(text) and not any(m in text for m in _REQUEST_MARKERS):
        return empty

    # 有工具倾向 → 按意图挑一句**对得上话茬儿**的垫场句；
    # 拿不准的疑问句 → 用通用兜底（仍要成句，不能是「等会儿」这种）。
    if any(k in lowered for k in _TOOL_HINTS):
        for pattern, pool, key in _INTENT_POOLS:
            if pattern.search(lowered):
                return _out(pool, key)
        return _out(_GENERIC_POOL, "generic")
    if text.endswith(("?", "？")) or any(
        w in text for w in ("多少", "几点", "几号", "星期几", "怎么", "为什么", "哪些", "哪个", "是不是")
    ):
        # 拿不准的疑问句：用**闲聊池**，不承诺动作
        # （主人 2026-10-07：玩游戏时说「行，我这就去处理」很别扭）
        return _out(_CHAT_POOL, "chat")

    # 纯陈述 / 自述：不播，等着就好
    # （2026-10-06 主人反馈「每说一句就回一个『好的』」：原来这里也兜底播，
    #   但陈述句 LLM 通常直接答、很快就出声，铺垫只是噪音，故收紧为不播）
    return empty
