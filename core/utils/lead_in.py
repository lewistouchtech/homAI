# [2026-10-13] 「谈论 / 评价 / 追问 / 陈述」不是「让它去办事」。
#
# 现象（主人 2026-10-13 10:58~11:02 实测）：主人在**评论过渡句功能本身**，
# 话里带着「音乐」「播放」「开关」「看看」这些词，整句被当成工具请求：
#   「音乐播放的8个缺陷，你再给我解释一下」   → 「我给你找找看」（music）
#   「那个降低量用开关方案是什么来着」          → 「好的」（action_device）
#   「呃，衔接的意思不对，你可以看看日志」      → 「来，我看一眼」（look）
#   「你说的意思是，音乐播放期间，如果用户说话，音乐会……」→ 「好的，这就给你放」
# 根因：只看关键词在不在，不看「这句话是在**命令**还是在**谈论**」。
#
# 判据（纯本地结构判断，<0.1ms，不引入模型调用——垫场句要在判停后立刻出声）：
#   ① 有明确的「办事指令」→ 一律按原逻辑走（命令优先，宁可多播不冷场）：
#      句首祈使动词 / 帮我·麻烦·请·能不能 / 我想听·我要看 / 提醒我 等
#   ② 否则，出现「谈论语境」标记 → 判为谈论：
#      元话语名词（缺陷/方案/逻辑/衔接…）、话语引导（你说的/我的意思是/刚才说…）、
#      评价反馈（不对/有问题/对不上…）、回忆追问（是什么来着）、
#      条件推演（如果……会……）、解释类动词（解释/讲讲/说说…）
#   谈论 + 在等回复（问句/解释类动词）→ 只应「我想想」（闲聊池，不承诺动作）；
#   谈论 + 纯陈述 → 不播。
