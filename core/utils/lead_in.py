def _is_discussion(text: str) -> bool:
    """这句话是在「谈论/评价/追问」而不是「让它去办事」。"""
    if _COMMAND_RE.search(text):
        return False
    if _DISCUSS_RE.search(text) or _CONTINUE_TALK_RE.search(text):
        return True
    return len(_norm(text)) >= _LONG_TALK_CHARS


