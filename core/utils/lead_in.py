"""前置过渡句：判停确认后立刻出声，填满等待时间。

## 为什么需要

主人实测「回复延时长」。生产日志拆解显示：判停到开口之间有约 3.5 秒完全静默
（LLM 首 token 就要 2~4.5 秒）。这段沉默才是体感的来源，不是总时长。

对话类问题 LLM 直接答，不需要铺垫；工具类问题要等工具执行 + LLM 二次总结，
这段等待是实打实的。过渡句就是在这段等待里出声，**总时长不变，感知延时降低**。

## 为什么放在判停之后、LLM 之前

原有过渡句实现在 `chat_engine.py:614`，触发时机是「LLM 已返回 tool_calls 之后」——
那时工具还没执行完，衔接语成了事后诸葛亮，一秒都没抢到。

前置到 `chat()` 开头，理由：
- 判停那一刻文本已就绪（A1 预判 + A2 指纹复用把判停压到 ~400ms）
- 不依赖工具名，所以不用等 LLM
- `run_coroutine_threadsafe` fire-and-forget，不阻塞主流程，主链路照原样推进

## 安全设计

**宁可多播一句「好的」，也不要该播的时候冷场。** 但闲聊场景多播会很怪，
所以用文本特征判断「是否可能需要等待」：

- 命中工具倾向关键词 → 播（宁可多播）
- 明确是闲聊/自述 → 不播
- 拿不准 → 播通用过渡句（「好的」这种在任何场合都不突兀）

纯本地正则匹配，实测 <0.1ms，不引入任何外部依赖。

## 【2026-10-12 改造】

主人原话（三条）：
①「过渡句长度按实际等待动态调整（工具/TTS 快则短、慢则长）」
②「过渡句内容与问题相关联但不复述问题」
③「过渡句较长还没说完时，TTS 回复要能排队接在其后，说完立刻接」

**①最终是「不按长度分档」，主人自己纠正了方向**：
「并没有限定超短句的回复，因为我们现在的做法已经不需要这种限制了……
  反正说长了，后面是排队嘛，这样就没有影响，反而显得更顺畅。
  一点延迟都没有，直接就接上了，反而更好。我觉得可以说长一点。」

技术原因：过渡句与正文回复走**同一个 `AudioRateController` FIFO**，
过渡句长不会给总时长加码（回复音频本来就排在它后面），说完直接接上、听感连贯；
短句反而突兀（「好的」→ 静默 → 突然一大段）。
所以 `Pool.for_budget()` 现在**返回全部候选**，随机轮换。

**②`pick_non_repeating()`**：候选句与用户原话有 ≥5 字连续重合即判为「复述」，
只在不复述的候选里挑；全复述才退回原池（宁可复述也不冷场）。

**③修的是竞态，不是排队**：排队机制本来就成立（同一 FIFO），真正的 bug 是
`conn.sentence_id` 在过渡句投递**之后**才重新生成 → 回复首帧到达时 `sendAudio`
发现 id 变了 → `reset()` 清空队列把过渡句截断。已在 `chat_engine.chat()` 修复
（稳定模块第 4 项，主人已授权）。

**语言风格（主人三次纠正后的标准）**：标准普通话 + 自然口语 + 全国通用。
禁方言（「好嘞」「瞅瞅」「咋」「弄」「干」）、禁客服腔（「请说」）、
也禁公文腔（「处理」）；但「稍等」「相关内容」是生活用语，保留。
"""

